/**
 * @brief Encodes two 16-bit values into a 32-bit Morton code.
 * 
 * @note We restrict inputs to 16-bit because scaling an 8-bit LUT method to 
 * 32-bit inputs requires too many memory lookups (8 array accesses), causing 
 * cache bottlenecks. For >16-bit inputs, prefer hardware intrinsics (e.g., PDEP) 
 * or magic numbers.
 * 
 * @param x 'X' coordinate
 * @param y 'Y' coordinate
 * @return uint32_t The 2D Z-order index
 */
[[nodiscard]] constexpr uint32_t MortonEncodeLut2d(uint16_t x, uint16_t y) noexcept {
    uint32_t x_32 = static_cast<uint32_t>(x);
    uint32_t y_32 = static_cast<uint32_t>(y);

    // Save cache misses by using only 1 LUT and shifting by 1 for Y.
    uint32_t answer =
        (internal::kMorton256X2d[(y_32 >> 8) & 0xFF] << 17) | //
        (internal::kMorton256X2d[(x_32 >> 8) & 0xFF] << 16) |
        (internal::kMorton256X2d[(y_32) & 0xFF] << 1) | //
        (internal::kMorton256X2d[(x_32) & 0xFF]);

    return answer;
}

/**
 * @brief Encodes three 21-bit values into a 64-bit Morton code.
 * 
 * @note Inputs are restricted to 21 bits (max 2,097,151) to fit inside a 
 * 64-bit output; larger values will be truncated. Furthermore, see the 
 * MortonEncodeLut2d note regarding LUT performance: this 3D version requires 
 * 9 memory lookups, making it highly prone to cache bottlenecks in hot loops.
 *
 * 
 * @param x 'X' coordinate
 * @param y 'Y' coordinate
 * @param z 'Z' coordinate
 * @return uint64_t The 3D Z-order index
 */
[[nodiscard]] constexpr uint64_t MortonEncodeLut3d(uint32_t x, uint32_t y, uint32_t z) noexcept {
    uint64_t answer;

    // Start by shifting the third byte, since we only look at the first 21 bits
    // and save cache misses by using only 1 LUT, by shifting with 1 for Y and with 2 for Z.
    answer = (static_cast<uint64_t>(internal::kMorton256X3d[(z >> 16) & 0xFF]) << 2) | //
        (static_cast<uint64_t>(internal::kMorton256X3d[(y >> 16) & 0xFF]) << 1) | //
        (static_cast<uint64_t>(internal::kMorton256X3d[(x >> 16) & 0xFF]));

    answer = (answer << 24) | // Shifting second byte.
        (static_cast<uint64_t>(internal::kMorton256X3d[(z >> 8) & 0xFF]) << 2) | //
        (static_cast<uint64_t>(internal::kMorton256X3d[(y >> 8) & 0xFF]) << 1) | //
        (static_cast<uint64_t>(internal::kMorton256X3d[(x >> 8) & 0xFF]));

    answer = (answer << 24) | // First byte.
        (static_cast<uint64_t>(internal::kMorton256X3d[(z) & 0xFF]) << 2) | //
        (static_cast<uint64_t>(internal::kMorton256X3d[(y) & 0xFF]) << 1) | //
        (static_cast<uint64_t>(internal::kMorton256X3d[(x) & 0xFF]));

    return answer;
}

